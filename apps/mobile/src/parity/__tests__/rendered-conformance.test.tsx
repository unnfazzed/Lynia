/**
 * RENDERED conformance — the CI-blocking half of the parity guardrail suite.
 *
 * The static guardrails read source: token values, the screen inventory, the mock's own AST. None of
 * them can see what a screen ACTUALLY paints once its data arrives — which conditional branch wins,
 * what the live wiring interpolates into a string, whether the app invented copy the mock never drew.
 * That blind spot is how the launcher home shipped ONE generic card reading "Delivery in progress"
 * while the mock draws TWO service-specific cards ("Sadza Republic · 6 min away" / "Cash at the door
 * · $15.50" / "Parcel to Msasa · rider 4 min away" / "Delivery code 4192 · $3.36").
 *
 * So this test mounts the REAL screen with the REAL parity fixture (the same
 * tools/parity/mobile/fixtures/*.mjs the screenshot lane stages — never a second copy of the data)
 * and compares its rendered text sequence, in order and in groups, against the expectation extracted
 * from the design mock (tools/parity/expected/<key>.json, committed, regenerated by
 * `node tools/parity/extract-expected.mjs`).
 *
 * No browser is involved here on purpose: browser rendering is environment-sensitive, which is why
 * the parity-render CI job is continue-on-error. The browser half runs offline and commits its
 * output; THIS half blocks.
 *
 * Escapes are per-string and reviewable, never blanket:
 *   - `dynamic` in the expected JSON — a mock string a fixture cannot pin (a geolocated address, a
 *     live clock). Requires a regex the app string must satisfy, plus a written reason.
 *   - `extra` in the expected JSON — an app string the mock does not draw. "Not drawn ⇒ not
 *     rendered" means the default is to DELETE it from the screen; an entry here is a reviewed
 *     exception with a reason.
 *   - tools/parity/rendered-conformance.pending.json — a wired+fixtured key not yet asserted at all,
 *     with an honest reason. A key that is in neither the expected set nor pending FAILS: no screen
 *     is silently uncovered.
 */
