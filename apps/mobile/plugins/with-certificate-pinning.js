// Expo config plugin: TLS certificate pinning for the API + WS host (SECURITY §P3-1).
//
// GATED BY DESIGN — a no-op unless real pins are supplied via the LYNIA_TLS_PINS env var, exactly like
// the Maps key / FCM file / EAS id in app.config.ts. An UNPINNED build is byte-identical to today, so
// merging this can never change or break a build. Pinning only takes effect once armed, and only in a
// fresh NATIVE build (it edits the Android network-security-config + iOS Info.plist, so it is NOT
// OTA-able — the fingerprint runtimeVersion shifts and a store release is required).
//
// ⚠️  Read docs/MOBILE-CERT-PINNING.md before arming. The API is behind a Google-managed cert that
//     AUTO-ROTATES. Pin an intermediate/root SPKI (Google Trust Services), NOT the leaf, and ALWAYS
//     include a backup pin — a wrong or backup-less pin bricks every installed app's connectivity on
//     the next rotation, unrecoverable without a forced update. The Android pin-set also carries an
//     `expiration` safety valve (pinning is bypassed past that date) — keep it ahead of your CA's
//     rotation cadence and refresh it on each release.
//
// LYNIA_TLS_PINS format: comma-separated base64 SHA-256 SPKI hashes, e.g.
//   LYNIA_TLS_PINS="sha256/AAAAAAAA...=,sha256/BBBBBBBB...="   (>= 2: primary + backup)
// Optional LYNIA_TLS_PIN_EXPIRATION="YYYY-MM-DD" (Android safety-valve date; defaults ~90 days out is
// NOT auto-computed here to keep the plugin deterministic — set it explicitly when arming).

const { withAndroidManifest, withInfoPlist, withDangerousMod, AndroidConfig } = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

/** Parse + validate the pins env. Returns null when unset (→ plugin is a no-op). Throws on a malformed
 *  value so an arming mistake fails the build loudly instead of silently shipping no protection. */
function parsePins() {
  const raw = process.env.LYNIA_TLS_PINS;
  if (!raw || !raw.trim()) return null;
  const pins = raw
    .split(",")
    .map((p) => p.trim())
    .filter(Boolean);
  for (const p of pins) {
    // Accept "sha256/<base64>" or a bare base64 SHA-256 (44 chars ending in "="). Reject anything else.
    const b64 = p.startsWith("sha256/") ? p.slice("sha256/".length) : p;
    if (!/^[A-Za-z0-9+/]{43}=$/.test(b64)) {
      throw new Error(`[cert-pinning] invalid pin "${p}" — expected a base64 SHA-256 SPKI hash (sha256/…=)`);
    }
  }
  if (pins.length < 2) {
    throw new Error("[cert-pinning] supply at least TWO pins (primary + backup) — a single pin bricks the app on rotation");
  }
  return pins.map((p) => (p.startsWith("sha256/") ? p.slice("sha256/".length) : p));
}

/** Extract the API host from app.config's extra.apiUrl (falls back to the known prod host). */
function apiHost(config) {
  const url = config?.extra?.apiUrl ?? "https://lyniago.lyniafinance.com";
  try {
    return new URL(url).hostname;
  } catch {
    return "lyniago.lyniafinance.com";
  }
}

const ANDROID_NSC = "network_security_config";

function androidNetworkSecurityXml(host, pins, expiration) {
  const pinEls = pins.map((digest) => `      <pin digest="SHA-256">${digest}</pin>`).join("\n");
  // cleartextTrafficPermitted=false: this host is HTTPS-only. The pin-set expiration is the safety valve.
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-certificate-pinning.js — do not hand-edit; change LYNIA_TLS_PINS instead. -->
<network-security-config>
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="false">${host}</domain>
    <pin-set expiration="${expiration}">
${pinEls}
    </pin-set>
  </domain-config>
</network-security-config>
`;
}

function withAndroidPinning(config, host, pins, expiration) {
  // 1) Point the manifest's <application> at the network-security-config resource.
  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$["android:networkSecurityConfig"] = `@xml/${ANDROID_NSC}`;
    return cfg;
  });
  // 2) Write the res/xml/network_security_config.xml file into the prebuilt android/ project.
  config = withDangerousMod(config, [
    "android",
    (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${ANDROID_NSC}.xml`), androidNetworkSecurityXml(host, pins, expiration), "utf8");
      return cfg;
    },
  ]);
  return config;
}

function withIosPinning(config, host, pins) {
  return withInfoPlist(config, (cfg) => {
    const ats = cfg.modResults.NSAppTransportSecurity ?? {};
    ats.NSPinnedDomains = {
      ...(ats.NSPinnedDomains ?? {}),
      [host]: {
        NSIncludesSubdomains: false,
        // iOS pins CA identities by SPKI SHA-256 (base64). Primary + backup, same list as Android.
        NSPinnedCAIdentities: pins.map((digest) => ({ "SPKI-SHA256-BASE64": digest })),
      },
    };
    cfg.modResults.NSAppTransportSecurity = ats;
    return cfg;
  });
}

/** @type {import('@expo/config-plugins').ConfigPlugin} */
module.exports = function withCertificatePinning(config) {
  const pins = parsePins();
  if (!pins) {
    // No pins supplied → leave the build exactly as it is today (unpinned, working).
    return config;
  }
  const host = apiHost(config);
  const expiration = process.env.LYNIA_TLS_PIN_EXPIRATION;
  if (!expiration || !/^\d{4}-\d{2}-\d{2}$/.test(expiration)) {
    throw new Error(
      "[cert-pinning] LYNIA_TLS_PINS is set but LYNIA_TLS_PIN_EXPIRATION (YYYY-MM-DD) is missing/invalid — " +
        "the Android pin-set expiration is a required safety valve. See docs/MOBILE-CERT-PINNING.md.",
    );
  }
  config = withAndroidPinning(config, host, pins, expiration);
  config = withIosPinning(config, host, pins);
  return config;
};
