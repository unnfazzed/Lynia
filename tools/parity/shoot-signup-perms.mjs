#!/usr/bin/env node
/**
 * Permissions right after sign-up (ledger D-109): the First Run v2 design each screen adapts (handoff
 * screenshots PC1, PC8, P1) beside the app screen rendered through react-native-web.
 *
 *   node tools/parity/shoot-signup-perms.mjs --out docs/parity/SIGNUP-PERMISSIONS-2026-10-15
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { contextDefaults, launch } from "./lib/browser.mjs";
import { buildSheet } from "./lib/sheet.mjs";
import { bundleScreen } from "./mobile/bundle.mjs";
import { interFontCss } from "./mobile/fonts.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "../..");
const outArg = process.argv.indexOf("--out");
const OUT = resolve(outArg > 0 ? process.argv[outArg + 1] : join(HERE, "out/signup-perms"));
const SHOTS = `${OUT}-shots`;
const HANDOFF = join(REPO, "packages/design/handoff/first-run-v2/screenshots");
const app = (p) => join(REPO, "apps/mobile/app", p);
const PHONE = { width: 360, height: 720 };

const ROWS = [
  { id: "location", label: "Customer · after sign-up · location", mock: "PC1.png", mockNote: "PC1, the Home sheet it adapts", component: app("setup-permissions.tsx"), fixture: "signup_perm_location" },
  { id: "notif", label: "Customer · after sign-up · order updates", mock: "PC8.png", mockNote: "PC8, without the Order placed pill", component: app("setup-permissions.tsx"), fixture: "signup_perm_notif" },
  { id: "rider", label: "Biker · after sign-up · P1", mock: "P1.png", mockNote: "P1, unchanged", component: app("permissions.tsx"), fixture: "signup_perm_rider" },
];

function harnessHtml(js, fontCss, vp) {
  return `<!doctype html><html><head><meta charset="utf-8"><style>
${fontCss}
html,body{margin:0;padding:0;background:#fff;}
#root{width:${vp.width}px;height:${vp.height}px;overflow:hidden;display:flex;flex-direction:column;
  font-family:"Inter",-apple-system,"Segoe UI",Roboto,sans-serif;}
#root>*{flex:1 1 auto;min-height:0;}
</style></head><body><div id="root"></div><script>${js}</script></body></html>`;
}

await mkdir(SHOTS, { recursive: true });
const browser = await launch();
const fontCss = await interFontCss();
const rows = [];
try {
  for (const r of ROWS) {
    const ctx = await browser.newContext(contextDefaults({ viewport: PHONE, deviceScaleFactor: 2 }));
    const page = await ctx.newPage();
    let shot = null;
    let note;
    try {
      const js = await bundleScreen({ component: r.component, fixture: join(HERE, "mobile/fixtures", `${r.fixture}.mjs`) });
      await page.setContent(harnessHtml(js, fontCss, PHONE), { waitUntil: "load" });
      await page.waitForFunction(() => window.__PARITY_READY === true || typeof window.__PARITY_ERROR === "string", { timeout: 20000 });
      const err = await page.evaluate(() => window.__PARITY_ERROR || null);
      if (err) throw new Error(err);
      await page.evaluate(() => (document.fonts ? document.fonts.ready : null));
      await page.waitForTimeout(1500);
      shot = join(SHOTS, `app-${r.id}.png`);
      await (await page.$("#root")).screenshot({ path: shot });
    } catch (e) {
      note = String(e.message || e).slice(0, 200);
    } finally {
      await ctx.close();
    }
    rows.push({ label: r.label, mock: join(HANDOFF, r.mock), mockNote: r.mockNote, app: shot, appNote: note, logicalW: PHONE.width });
    console.log(`${r.id}: ${shot ? "ok" : `app failed — ${note}`}`);
  }
} finally {
  await browser.close();
}
await buildSheet({ title: "Permissions right after sign-up (D-109): the First Run v2 design it adapts (left) vs app (right)", out: OUT, rows });
await writeFile(`${SHOTS}/README.txt`, "Generated by tools/parity/shoot-signup-perms.mjs\n");
console.log(`sheet: ${OUT}.png (+ .html); shots in ${SHOTS}`);
